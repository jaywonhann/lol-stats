const batchim = (w: string) => {
  const c = w.trim().charCodeAt(w.trim().length - 1) - 0xac00;
  return c >= 0 && c <= 11171 ? c % 28 : 0;
};
const eun = (w: string) => `${w}${batchim(w) ? "은" : "는"}`;
const ro = (w: string) => `${w}${batchim(w) && batchim(w) !== 8 ? "으로" : "로"}`;

